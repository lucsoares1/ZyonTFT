import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import {execFile} from "node:child_process";
import {promisify} from "node:util";
import {_electron as electron} from "playwright";
import {planForLevel} from "../src/level-planner.mjs";

const {version}=JSON.parse(await fs.readFile("package.json","utf8"));
const out=path.resolve(`design/review/${version}/team-levels`);
await fs.mkdir(out,{recursive:true});
const profile=path.resolve(".runtime",`team-levels-${Date.now()}`);
const env={...process.env,ZYON_USER_DATA:profile,ZYON_OVERLAY_PREVIEW:"1",ZYON_OCR_FIXTURE:path.resolve("design/references/17-game-ocr.png")};
delete env.ELECTRON_RUN_AS_NODE;delete env.ZYON_DEV_URL;
const packaged=process.argv.includes("--packaged"),suffix=packaged?"-packaged":"";
const app=await electron.launch({...packaged?{executablePath:path.resolve(process.env.ZYON_TEST_EXE||"release/win-unpacked/Zyon TFT.exe"),args:[]}:{args:["."]},env});
const checks=[],errors=[];
const catalog=Object.fromEntries(JSON.parse(await fs.readFile("src/generated/catalog.json","utf8")).champions.map(c=>[c.id,c]));
try{
 const page=await app.firstWindow();
 page.on("pageerror",e=>errors.push(e.message));
 await page.getByRole("heading",{name:"Composições",exact:true}).waitFor();
 await page.locator(".overlay-toggle").click();
 const waitState=async predicate=>{const until=Date.now()+35000;while(Date.now()<until){const s=await page.evaluate(()=>window.zyon.getState());if(predicate(s))return s;await page.waitForTimeout(100);}throw Error("Expected session not reached");};
 let state=await waitState(s=>s.levelReading.level===7&&s.goldReading.gold===18&&s.guideComp);
 const guide=app.windows().find(w=>w.url().includes("view=guide"));
 assert.ok(guide);guide.on("pageerror",e=>errors.push(e.message));
 await guide.getByRole("tab",{name:"Equipe",exact:true}).click();
 await guide.getByRole("heading",{name:"Quem joga agora",exact:true}).waitFor();
 const liveButton=guide.getByRole("button",{name:/^Agora · Nv\./});
 assert.equal(await liveButton.getAttribute("aria-pressed"),"true");
 const capture=async name=>{await guide.evaluate(()=>document.fonts.ready);await guide.waitForFunction(()=>[...document.images].every(i=>i.complete&&i.naturalWidth>0));await guide.screenshot({path:path.join(out,`${name}${suffix}.png`),omitBackground:true});};
 await capture("live-level7");
 const before=(await page.evaluate(()=>window.zyon.getState())).gameSession;
 const expectedBoard=async ids=>assert.deepEqual((await guide.locator(".game-team-info .game-unit").evaluateAll(nodes=>nodes.map(n=>n.dataset.unit))).sort(),[...ids].sort());
 for(let level=1;level<=10;level++){
  await guide.getByRole("button",{name:`Consultar nível ${level}`,exact:true}).click();
  await guide.getByRole("heading",{name:`Equipe no nível ${level}`,exact:true}).waitFor();
  const plan=planForLevel(state.guideComp,catalog,{...before.context,level});
  await expectedBoard(plan.team.ids);
  assert.equal(await guide.locator(".game-team-board .tft-hex.occupied").count(),plan.team.ids.length);
  const expectedItems=Object.values(plan.equipment).flat().sort();
  const actualItems=await guide.locator(".game-team-board .hex-equipment img").evaluateAll(nodes=>nodes.map(n=>decodeURIComponent(n.getAttribute("src").split("/").at(-1).slice(0,-4))).sort());
  assert.deepEqual(actualItems,expectedItems);
  const transition=await guide.locator(".game-transition").innerText();
  for(const id of [...plan.entering,...plan.leaving])assert.ok(transition.includes(catalog[id].name));
  assert.deepEqual((await page.evaluate(()=>window.zyon.getState())).gameSession,before,"consultation must never mutate level, gold, purchases or copies");
 }
 checks.push("all ten levels update board, equipment, units and transitions without changing the live session");
 await guide.getByRole("button",{name:"Consultar nível 8",exact:true}).click();
 await capture("preview-level8");
 // A real labelled level9 crop drives an OCR update while level8 is consulted.
 const composite=path.join(out,"level9-composite.png");
 await promisify(execFile)("powershell.exe",["-NoProfile","-NonInteractive","-ExecutionPolicy","Bypass","-File","scripts/create-level9-fixture.ps1","-BasePath",path.resolve("design/references/17-game-ocr.png"),"-LevelPath",path.resolve("design/references/41-level9-stale8.png"),"-OutputPath",composite],{windowsHide:true});
 await page.evaluate(()=>window.zyon.setReader(false));
 await app.evaluate(({},file)=>{process.env.ZYON_OCR_FIXTURE=file;},composite);
 await page.evaluate(()=>window.zyon.setReader(true));
 state=await waitState(s=>s.levelReading.level===9&&s.gameSession.context.level===9);
 assert.equal(await guide.getByRole("button",{name:"Consultar nível 8",exact:true}).getAttribute("aria-pressed"),"true");
 await guide.getByRole("heading",{name:"Equipe no nível 8",exact:true}).waitFor();
 await liveButton.click();
 await guide.getByRole("heading",{name:"Quem joga agora",exact:true}).waitFor();
 await expectedBoard(planForLevel(state.guideComp,catalog,state.gameSession.context).team.ids);
 assert.equal(await guide.getByRole("button",{name:"Consultar nível 9",exact:true}).getAttribute("aria-pressed"),"true");
 checks.push("OCR advancement to level9 preserves the chosen level8 preview; Agora returns to the new live level");
 await guide.getByRole("button",{name:"Equipe final",exact:true}).click();
 await expectedBoard(state.guideComp.champions);
 assert.equal(await guide.locator(".game-transition").count(),0,"final preview cannot show an unrelated live-level transition");
 await guide.getByRole("button",{name:"Consultar nível 3",exact:true}).click();
 await guide.getByRole("heading",{name:"Equipe no nível 3",exact:true}).waitFor();
 await guide.getByRole("tab",{name:"Agora",exact:true}).click();
 assert.ok((await guide.locator(".game-now-layout .tft-hex.occupied").count())>3,"Agora board must use level9, not the browsed level3");
 await guide.getByRole("tab",{name:"Equipe",exact:true}).click();
 await guide.getByRole("heading",{name:"Equipe no nível 3",exact:true}).waitFor();
 checks.push("final and earlier previews stay local to Equipe; Agora keeps the live plan");
 await app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes("view=guide"));w.setBounds({...w.getBounds(),width:640});});
 await guide.waitForFunction(()=>innerWidth===640);
 const geometry=await guide.locator(".game-team-levels").evaluate(root=>{const r=root.getBoundingClientRect();return [...root.children].map(el=>{const b=el.getBoundingClientRect();return{left:b.left,right:b.right,width:b.width,within:b.left>=r.left&&b.right<=r.right+1};});});
 assert.ok(geometry.every(b=>b.within&&b.width>=25));
 await capture("preview-level3-narrow");
 checks.push("level controls fit the 840px and 640px native guide without horizontal overflow");
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,`checks${suffix}.json`),JSON.stringify({ok:true,checks,geometry,note:"Isolated profile, real screenshot OCR; level9 update uses an explicit composite from screenshots17/41. No live game input."},null,2));
 console.log(JSON.stringify({ok:true,checks}));
}finally{await app.close();}
