 await waitState(s=>s.gameSession.context.copies[id]===1);
 const changeFixture=async file=>{await page.evaluate(()=>window.zyon.setReader(false));await app.evaluate(({ },value)=>{process.env.ZYON_OCR_FIXTURE=value;},file);await page.evaluate(()=>window.zyon.setReader(true));};
 await changeFixture(composite);
